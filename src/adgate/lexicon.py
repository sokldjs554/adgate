from __future__ import annotations

import re
from dataclasses import dataclass


@dataclass(frozen=True)
class Pat:
    name: str
    rx: re.Pattern[str]
    negatable: bool = False  # 뒤에 부정 표현이 오면 위반이 아닌 패턴(수익 보장 → 수익을 보장하지 않습니다)
    txn_after: bool = False  # 뒤에 거래 조건(환불·교환·체험 …)이 오면 위반이 아닌 패턴(손해 없이 환불해 드립니다)


def _c(name: str, pattern: str, negatable: bool = False, txn_after: bool = False) -> Pat:
    return Pat(name, re.compile(pattern), negatable, txn_after)


