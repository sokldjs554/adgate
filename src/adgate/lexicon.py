# 패턴 바로 뒤(같은 절 안, 조사·명사 몇 글자 이내)에 서술어 부정이 오면 위반이 아니라 면책·경고 문구다.
# '걱정 없이'처럼 멀리 떨어진 부사 '없이'는 부정이 아니다(T-048). '없이'는 FRD 의 '입력 없이'처럼 바로 뒤일 때만 쓴다.
# 부정은 패턴(보장·승인 …)의 *서술어*여야 한다: 조사 한 개, 또는 '상품이'·'형이' 같은 짧은 명사 + 조사만 건너뛴다.
# '걱정 없습니다', '문제 없어요' 처럼 다른 명사가 끼면 부정이 아니다("원금 보장 걱정 없습니다" 는 보장하겠다는 말이다 — F-2, 독립 리뷰 H3).
_NEG_SKIP = r"(?:(?:상품|제품|형태|형|구조|방식|서비스|프로그램|대출|투자)?(?:이란|이라고는|으로는|은|는|이|가|을|를|도|만|란)?(?:달라고|하라고|라고)?(?:주지)?)"
NEG_NEAR = re.compile(
    rf"^{_NEG_SKIP}(?:하지(?:는|도)?않|되지(?:는|도)?않|해?드리지(?:는|도)?않|않(?:습니다|아요|으며|고|는다|음)|아닙니다|아니며|아니라|아니고|아닌|아님"
    r"|불가|못(?:합|해|하|됩|되)|안됩니다|안돼|할수없|수는없|수없|없(?:습니다|음|어요|다)|어렵|여부|마세요|말라|말고|금지)"
)
NEG_WITHOUT = re.compile(r"^없이")
BOUNDARY = re.compile(r"[!?.,;:\n]")
TAIL_MAX = 14


def negated(tight: str, end: int, *, without: bool = False) -> bool:
    """tight[end:] 의 같은 절 안에서, 패턴 바로 뒤에 서술어 부정이 오는가."""
    m = BOUNDARY.search(tight, end, end + TAIL_MAX)
    stop = m.start() if m else min(len(tight), end + TAIL_MAX)
    tail = tight[end:stop]
    return NEG_NEAR.match(tail) is not None or (without and NEG_WITHOUT.match(tail) is not None)


# 사기 경고 문구: "선입금·선수수료·보증료나 인증번호를 요구하지 않습니다" 처럼 명사 나열 뒤에 '요구하지 않는다'가 오는 경우.
# 같은 절 안(40자 이내)에서 요구 부정이 나오되, 그 사이에 요청·명령 표현이 끼면("선입금하세요 … 요구하지 않습니다") 면책으로 보지 않는다.
REQUEST_NEG = re.compile(r"(?:요구|요청|청구|받|묻|안내|문의)(?:하지|지)\s*않")
REQUEST_MARK = re.compile(r"세요|십시오|바랍니다|필요|해야|하셔야|부탁")
REQUEST_WINDOW = 40


def negated_request(tight: str, end: int) -> bool:
    m = BOUNDARY.search(tight, end, end + REQUEST_WINDOW)
    stop = m.start() if m else min(len(tight), end + REQUEST_WINDOW)
    tail = tight[end:stop]
    neg = REQUEST_NEG.search(tail)
    return neg is not None and REQUEST_MARK.search(tail[: neg.start()]) is None


